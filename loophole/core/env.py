"""Environment base class, the registry, and content addressed splits."""

from __future__ import annotations

import hashlib
from abc import ABC, abstractmethod
from collections.abc import Callable
from typing import ClassVar

from loophole.core.types import Task, Verifier

SPLITS = ("train", "val", "test")


def split_of(key: str, val_frac: float = 0.1, test_frac: float = 0.1) -> str:
    """Assign a split from a hash of the task's content, never from its position.

    A task generated by seed 3 and the same task generated by seed 7 land in the
    same split, so no seed choice can leak a test task into training.
    """
    h = int.from_bytes(hashlib.sha256(key.encode()).digest()[:8], "big") / 2**64
    if h < test_frac:
        return "test"
    if h < test_frac + val_frac:
        return "val"
    return "train"


class Environment(ABC):
    """A family of tasks plus the two verifiers that grade them.

    Subclasses declare, in plain words, the exploit that their leaky verifier
    admits. The exploit is documented up front on purpose: the experiment is
    whether training discovers a known hole, not whether a hole exists.
    """

    name: ClassVar[str]
    exploit: ClassVar[str]
    exploit_class: ClassVar[str]
    multi_turn: ClassVar[bool] = False

    @abstractmethod
    def candidates(self, seed: int) -> Callable[[], Task | None]:
        """Return a generator function yielding fresh candidate tasks for this seed."""

    @abstractmethod
    def verifiers(self) -> dict[str, Verifier]:
        """Must contain at least "honest" and "leaky"."""

    def generate(self, n: int, seed: int, split: str, max_tries: int | None = None) -> list[Task]:
        if split not in SPLITS:
            raise ValueError(f"unknown split {split!r}")
        draw = self.candidates(seed)
        out: list[Task] = []
        seen: set[str] = set()
        tries = 0
        limit = max_tries or n * 50
        while len(out) < n and tries < limit:
            tries += 1
            t = draw()
            if t is None or t.split != split or t.task_id in seen:
                continue
            seen.add(t.task_id)
            out.append(t)
        if len(out) < n:
            raise RuntimeError(f"{self.name}: only {len(out)} of {n} {split} tasks after {tries} draws")
        return out


_REGISTRY: dict[str, type[Environment]] = {}


def register(cls: type[Environment]) -> type[Environment]:
    if cls.name in _REGISTRY:
        raise ValueError(f"environment {cls.name!r} registered twice")
    _REGISTRY[cls.name] = cls
    return cls


def get_env(name: str, **kwargs) -> Environment:
    import loophole.envs  # noqa: F401  (registers every environment)

    if name not in _REGISTRY:
        raise KeyError(f"unknown environment {name!r}; known: {sorted(_REGISTRY)}")
    return _REGISTRY[name](**kwargs)


def env_names() -> list[str]:
    import loophole.envs  # noqa: F401

    return sorted(_REGISTRY)
