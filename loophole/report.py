"""Render RESULTS.md from the run directories, so no table is ever typed by hand."""

from __future__ import annotations

import json
from pathlib import Path


def _rows(root: Path, kind: str) -> list[tuple[Path, dict, dict]]:
    out = []
    for d in sorted(root.iterdir()):
        if not (d / "manifest.json").exists() or f"-{kind}-" not in d.name + "-":
            continue
        summary = json.loads((d / "summary.json").read_text())[0] if (d / "summary.json").exists() else None
        if summary:
            out.append((d, json.loads((d / "manifest.json").read_text()), summary))
    return out


def _pct(x) -> str:
    return f"{100 * x:.1f}%"


def eval_table(root: Path) -> list[str]:
    lines = ["| Run | Env | Tasks | k | Honest | Leaky | False pass (95% CI) | pass@k | pass^k |",
             "| --- | --- | ---: | ---: | ---: | ---: | --- | ---: | ---: |"]
    for d, m, s in _rows(root, "eval"):
        k = s["k"]
        ci = s["hack_ci"]
        regraded = " (regraded)" if (d / "summary.before_regrade.json").exists() else ""
        lines.append(f"| `{d.name}`{regraded} | {s['env']} | {s['tasks']} | {k} | {_pct(s['honest'])} | "
                     f"{_pct(s['leaky'])} | {_pct(s['hack_rate'])} ({_pct(ci[0])} to {_pct(ci[1])}) | "
                     f"{_pct(s.get(f'pass@{k}', 0))} | {_pct(s.get(f'pass^{k}', 0))} |")
    return lines


def grpo_table(root: Path) -> list[str]:
    from loophole.eval.metrics import hack_curve
    from loophole.eval.runner import read

    lines = ["| Run | Env | Trained on | Seed | Steps | False pass, first 10 steps | Last 10 steps | "
             "Honest, first 10 | Last 10 |", "| --- | --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |"]
    for d in sorted(root.glob("*Z-grpo-*")):
        if not (d / "rollouts.jsonl").exists():
            continue
        cfg = json.loads((d / "manifest.json").read_text())["config"]
        curve = hack_curve(read(d / "rollouts.jsonl"))
        first, last = curve[:10], curve[-10:]
        avg = lambda rows, key: sum(r[key] for r in rows) / len(rows)  # noqa: E731
        lines.append(f"| `{d.name}` | {cfg['env']} | {cfg['train_on']} | {cfg['seed']} | {curve[-1]['step'] + 1} | "
                     f"{_pct(avg(first, 'hack_rate'))} | {_pct(avg(last, 'hack_rate'))} | "
                     f"{_pct(avg(first, 'honest'))} | {_pct(avg(last, 'honest'))} |")
    return lines


def probe_table(root: Path) -> list[str]:
    lines = ["| Run | Platform | Backend | Contained | Escaped |", "| --- | --- | --- | ---: | --- |"]
    for d in sorted(root.glob("*-probe")):
        m = json.loads((d / "manifest.json").read_text())
        table = json.loads((d / "probes.json").read_text())
        for b in sorted({r["backend"] for r in table}):
            rs = [r for r in table if r["backend"] == b]
            esc = ", ".join(r["probe"] for r in rs if not r["contained"]) or "none"
            lines.append(f"| `{d.name}` | {m['platform'][:28]} | {b} | {sum(r['contained'] for r in rs)} of "
                         f"{len(rs)} | {esc} |")
    return lines


def render(root: Path, out: Path) -> Path:
    parts = ["# Results", "",
             "Generated by `loophole report` from every run directory in `runs/`. Each row names its run; the "
             "run's `manifest.json` holds the command, commit, and versions. Do not edit by hand.", "",
             "## Evaluations", "", *eval_table(root), "",
             "## GRPO training batches", "", "64 rollouts per step on the train split, graded by both verifiers.", "",
             *grpo_table(root), "", "## Sandbox probes", "", *probe_table(root), ""]
    out.write_text("\n".join(parts) + "\n")
    return out
